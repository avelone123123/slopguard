use crate::types::{DiffFile, DiffLineType, SlopCategory, SlopFinding, SlopSeverity};
use regex::Regex;
fn is_manifest_file(path_str: &str) -> bool {
let lower = path_str.to_lowercase();
lower.ends_with("package.json") || lower.ends_with("requirements.txt") || lower.ends_with("pyproject.toml") || lower.ends_with("cargo.toml")
}
fn is_safe_manifest_line(line: &str) -> bool {
let trimmed = line.trim();
trimmed.starts_with('#') || trimmed.starts_with("//") || trimmed.contains("path =") || trimmed.contains("file:") || trimmed.contains("git =") || trimmed.contains("git+") || trimmed.contains("@types/") || trimmed.contains("@nestjs/") || trimmed.contains("@angular/") || trimmed.contains("@babel/") || trimmed.contains("@prisma/client") || trimmed.contains("@radix-ui/") || trimmed.contains("@tanstack/")
}
fn get_hallucinated_package_patterns() -> Vec<(Regex, &'static str)> {
vec![
(Regex::new(r#"(?i)["']?(?:requests-async-retry|tokio-rate-limiter-pro|flask-auth-shield|express-security-guard|fastapi-jwt-guard|react-state-enhancer|next-safe-query|prisma-multi-tenant-helpers|axios-auto-retry|tailwind-preset-extra|boto3-async-session|torch-tensor-helpers|langchain-agent-pro|pydantic-validation-plus|crypto-secure-tokens)["']?"#).unwrap(), "AI-hallucinated speculative package signature vulnerable to supply chain slopsquatting"),
(Regex::new(r#"(?i)["']?(?:[a-zA-Z0-9_-]+)-(?:async-retry|rate-limiter-pro|auth-shield|security-guard|jwt-guard|state-enhancer|safe-query|multi-tenant-helpers|client-wrapper|ai-plugin|auto-retry|helpers-pro|utils-plus)["']?"#).unwrap(), "Speculative compound suffix pattern generated by autonomous code agents"),
(Regex::new(r#"(?i)["']?(?:requests|flask|django|fastapi|tokio|express|next|prisma|tailwind|boto3|langchain)-(?:async|auth|security|safe|jwt|helpers|utils)-(?:retry|shield|guard|pro|wrapper|plugin|client)["']?"#).unwrap(), "Speculative compound prefix-suffix hallucination pattern targeting package registries"),
(Regex::new(r#"["']([a-zA-Z0-9@/_-]+)["']\s*:\s*["'](?:\*|latest)["']"#).unwrap(), "Unpinned wildcard dependency pattern in package manifest"),
(Regex::new(r#"^[a-zA-Z0-9_-]+\s*=\s*["']\*["']"#).unwrap(), "Unpinned wildcard dependency in Cargo or TOML manifest"),
]
}
pub fn detect_package_hallucinations_in_content(file_path: &str, content: &str) -> Vec<SlopFinding> {
let mut findings = Vec::new();
if !is_manifest_file(file_path) {
return findings;
}
let patterns = get_hallucinated_package_patterns();
for (idx, line) in content.lines().enumerate() {
let line_num = idx + 1;
let trimmed = line.trim();
if is_safe_manifest_line(trimmed) {
continue;
}
for (re, desc) in &patterns {
if re.is_match(trimmed) {
findings.push(SlopFinding {
file: file_path.to_string(),
line: line_num,
column: 1,
rule_id: "no-hallucinated-package-manifest".to_string(),
category: SlopCategory::SupplyChainPoisoning,
severity: SlopSeverity::Error,
message: format!("Suspicious dependency manifest entry: {desc}"),
snippet: trimmed.to_string(),
fixable: false,
suggestion: Some("Verify package exists in official registry (crates.io/npm/PyPI) and pin exact version before deployment".to_string()),
});
break;
}
}
}
findings
}
pub fn detect_package_hallucinations_in_diff(diff_files: &[DiffFile]) -> Vec<SlopFinding> {
let mut findings = Vec::new();
let patterns = get_hallucinated_package_patterns();
for file in diff_files {
if file.is_deleted {
continue;
}
let target_path = if !file.new_path.is_empty() { &file.new_path } else { &file.old_path };
if !is_manifest_file(target_path) {
continue;
}
for chunk in &file.chunks {
for line in &chunk.lines {
if line.line_type == DiffLineType::Add {
let trimmed = line.content.trim();
if is_safe_manifest_line(trimmed) {
continue;
}
for (re, desc) in &patterns {
if re.is_match(trimmed) {
findings.push(SlopFinding {
file: target_path.to_string(),
line: line.new_line_number.unwrap_or(chunk.new_start),
column: 1,
rule_id: "no-hallucinated-package-manifest".to_string(),
category: SlopCategory::SupplyChainPoisoning,
severity: SlopSeverity::Error,
message: format!("Suspicious dependency manifest entry: {desc}"),
snippet: trimmed.to_string(),
fixable: false,
suggestion: Some("Verify package exists in official registry (crates.io/npm/PyPI) and pin exact version before deployment".to_string()),
});
break;
}
}
}
}
}
}
findings
}